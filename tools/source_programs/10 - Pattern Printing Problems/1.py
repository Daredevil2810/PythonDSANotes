# Solid Rectangle Pattern :

rows = int(input("Enter number of rows: "))
cols = int(input("Enter number of columns: "))

for i in range(rows):
    for j in range(cols):
        print("*", end="")
    print()


# Output : 

# Enter number of rows: 3
# Enter number of columns: 5
# *****
# *****
# *****