"""Build assets/js/lessons-python.js and verify every runnable code block.
Run from anywhere:  python3 tools/lessons/build_lessons.py

- Blocks whose output is AUTO get the real output of a run, so it can never be wrong.
- Blocks/try-its flagged plot=True are run with Matplotlib's Agg backend; the chart that plt.show() would display
  is saved to assets/img/plots/ and shown under the code on the lesson page.
"""
import json, os, subprocess, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, here)
import part1, part2, part3, part4, part5
from PIL import Image
AUTO = part3.AUTO
L = part1.LESSONS
ROOT = os.path.abspath(os.path.join(here, "..", ".."))
OUT = os.path.join(ROOT, "assets", "js", "lessons-python.js")
PLOTS = os.path.join(ROOT, "assets", "img", "plots")
os.makedirs(PLOTS, exist_ok=True)
for f in os.listdir(PLOTS):          # regenerate from scratch so removed charts do not linger
    if f.endswith(".png"): os.remove(os.path.join(PLOTS, f))

PRE = '''import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as _plt
def _show(*a, **k):
    _plt.savefig(%r, dpi=100, bbox_inches="tight", facecolor="white")
    _plt.close("all")
_plt.show = _show
'''

def run(code, cwd, plot_path=None, mpl=False):
    pre = (PRE % plot_path) if (plot_path or mpl) else ""
    r = subprocess.run([sys.executable, "-c", pre + code], capture_output=True, text=True, cwd=cwd, timeout=60)
    return r.stdout.rstrip("\n"), r.stderr

def attach_image(obj, rel_name, plot_path, where):
    global bad
    if not os.path.exists(plot_path):
        bad += 1; print("NO IMAGE", where); return
    if not obj.get("alt"): bad += 1; print("MISSING ALT", where)
    w, h = Image.open(plot_path).size
    obj["image"] = "assets/img/plots/" + rel_name; obj["iw"] = w; obj["ih"] = h

bad = 0
for les in L:
    mpl = les.get("lib") == "matplotlib"
    with tempfile.TemporaryDirectory() as d:
        for n, b in enumerate(les["blocks"], 1):
            if b.get("noRun"): continue
            name = "%s-%d.png" % (les["id"], n)
            pp = os.path.join(PLOTS, name) if b.get("plot") else None
            out, err = run(b["code"], d, pp, mpl)
            if b.get("output") == AUTO: b["output"] = out
            if err.strip() and "Warning" in err: print("WARNING", les["id"], b["title"], err.strip()[-300:])
            exp = b["output"].rstrip("\n")
            if out.strip() != exp.strip() or (err.strip() and "Warning" not in err):
                bad += 1; print("MISMATCH", les["id"], b["title"]); print(" expected:", repr(exp)); print(" got     :", repr(out), err[-300:])
            if b.get("plot"): attach_image(b, name, pp, les["id"] + " / " + b["title"])
        t = les["tryit"]
        with tempfile.TemporaryDirectory() as d2:
            name = "%s-try.png" % les["id"]
            pp = os.path.join(PLOTS, name) if t.get("plot") else None
            out, err = run(t["solution"], d2, pp, mpl)
            if t.get("output") == AUTO: t["output"] = out
            if out.strip() != t["output"].strip() or (err.strip() and "Warning" not in err):
                bad += 1; print("TRY MISMATCH", les["id"]); print(" expected:", repr(t["output"])); print(" got     :", repr(out), err[-300:])
            if t.get("plot"): attach_image(t, name, pp, les["id"] + " / try it")
print("lessons:", len(L), "problems:", bad, "| charts:", len(os.listdir(PLOTS)))
if bad: sys.exit(1)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// AUTO-GENERATED by tools/lessons/build_lessons.py\nwindow.PYDSA_LESSONS = " + json.dumps(L, ensure_ascii=False) + ";\n")
